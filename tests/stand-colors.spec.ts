import { test, expect } from '@playwright/test';
import AxeBuilder from '@axe-core/playwright';
import { mkdir } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const review = fileURLToPath(new URL('../test-results/review/stand-colors/', import.meta.url));

test('the plus opens a color wheel with HEX, keyboard, brightness, apply/cancel and persistent print colors', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.goto('/shop');
  const trigger = page.getByRole('button', { name: 'اختار لون مخصص', exact: true });
  const dialog = page.locator('.stand-color-dialog');
  const background = page.getByRole('textbox', { name: 'لون الخلفية — HEX', exact: true });
  const ink = page.getByRole('textbox', { name: 'لون النص — HEX', exact: true });
  const wheel = page.getByRole('slider', { name: 'عجلة الألوان', exact: true });
  await expect(dialog).not.toBeVisible();
  await trigger.click();
  await expect(dialog).toBeVisible();
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('hidden');
  await background.fill('#zzzzzz');
  await background.press('Tab');
  await expect(background).toHaveAttribute('aria-invalid', 'true');
  await background.fill('#7C7C7C');
  await expect(ink).toHaveValue('#000000');
  await background.fill('36a');
  await background.press('Tab');
  await expect(background).toHaveValue('#3366AA');
  await expect(ink).toHaveValue('#FFFFFF');
  await ink.fill('#3366AA');
  await page.getByRole('button', { name: 'ظبّط وضوح النص', exact: true }).click();
  await expect(ink).toHaveValue('#FFFFFF');
  await page.getByRole('button', { name: 'رجّع الألوان الجاهزة', exact: true }).click();
  await expect(background).toHaveValue('#FFF8EF');
  const box = (await wheel.boundingBox())!;
  await wheel.click({ position: { x: box.width * .9, y: box.height * .5 } });
  await expect(background).not.toHaveValue('#FFF8EF');
  const selected = await background.inputValue();
  await wheel.press('ArrowRight');
  await expect(background).not.toHaveValue(selected);
  const brightness = page.getByRole('slider', { name: 'سطوع اللون', exact: true });
  await brightness.press('Home');
  await expect(background).toHaveValue('#000000');
  await brightness.press('End');
  await expect(background).not.toHaveValue('#000000');
  await page.getByRole('button', { name: 'إلغاء', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(trigger).toBeFocused();
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('');
  await trigger.click();
  await expect(background).toHaveValue('#FFF8EF');
  await background.fill('#5B3CC4');
  await page.getByRole('button', { name: 'تطبيق الألوان', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await trigger.click();
  await background.fill('#FF0000');
  await background.press('Escape');
  await expect(dialog).not.toBeVisible();
  await trigger.click();
  await expect(background).toHaveValue('#5B3CC4');
  await page.getByRole('button', { name: 'تطبيق الألوان', exact: true }).click();
  await page.getByRole('textbox', { name: 'اسم البراند', exact: true }).fill('لون براندك');
  await page.getByRole('button', { name: 'احفظ التصميم للجاي', exact: true }).click();
  await page.reload();
  await trigger.click();
  await expect(background).toHaveValue('#5B3CC4');
  await expect(ink).toHaveValue('#FFFFFF');
  await background.fill('#1C4D8D');
  await page.getByRole('button', { name: 'تطبيق الألوان', exact: true }).click();
  await expect(page.locator('.shop-purchase-panel .shop-summary-total')).toContainText('٣٥٠');
  await page.getByRole('button', { name: 'عرض 3D · 360°', exact: true }).click();
  await expect(page.locator('.stand-3d-viewer')).toHaveAttribute('data-state', 'ready');
  const scene = page.locator('.stand-3d-canvas');
  const revision = Number(await scene.getAttribute('data-artwork'));
  await trigger.click();
  await background.fill('#7C3F61');
  await page.getByRole('button', { name: 'تطبيق الألوان', exact: true }).click();
  await expect.poll(async () => Number(await scene.getAttribute('data-artwork'))).toBeGreaterThan(revision);
  await mkdir(review, { recursive: true });
  for (const language of ['ar', 'en']) {
    if (language === 'en') await page.getByRole('button', { name: 'Switch to English', exact: true }).click();
    const open = page.getByRole('button', { name: language === 'ar' ? 'اختار لون مخصص' : 'Choose a custom color', exact: true });
    await open.click();
    for (const width of [1440, 390, 320]) {
      await page.setViewportSize({ width, height: width === 1440 ? 900 : 844 });
      await dialog.getByRole('slider', { name: language === 'ar' ? 'عجلة الألوان' : 'Color wheel', exact: true }).scrollIntoViewIfNeeded();
      await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
      await expect(page.getByRole('button', { name: language === 'ar' ? 'تطبيق الألوان' : 'Apply colors', exact: true })).toBeInViewport();
      await page.screenshot({ path: `${review}/wheel-${language}-${width}.png` });
    }
    expect((await new AxeBuilder({ page }).include('.stand-color-dialog').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze()).violations).toEqual([]);
    await page.getByRole('button', { name: language === 'ar' ? 'إلغاء' : 'Cancel', exact: true }).click();
  }
  await page.getByRole('button', { name: 'Add your design to bag', exact: true }).click();
  await page.getByRole('button', { name: 'View bag', exact: true }).click();
  await expect(page.locator('.shop-order-colors')).toContainText('#7C3F61');
  await page.getByRole('button', { name: 'Edit design', exact: true }).click();
  await page.getByRole('button', { name: 'Choose a custom color', exact: true }).click();
  await expect(page.getByRole('textbox', { name: 'Background color — HEX', exact: true })).toHaveValue('#7C3F61');
});
